"""
引用提示词模板
指导 LLM 在生成内容时嵌入 [ID:xxx] 格式的引用标记
"""


def get_citation_prompt() -> str:
    """
    返回引用规则提示词，追加到 system prompt 末尾。
    LLM 在生成回答时会根据此规则在合适的位置嵌入 [ID:xxx] 引用。
    """
    return """

## 引用规则

你的回答中必须使用 `[ID:数字]` 格式标注参考来源。请严格遵循以下规则：

### 格式要求
- 单个引用：`[ID:327]`
- 多个引用：`[ID:327] [ID:45]`（用空格分隔，不要用逗号）
- 位置：放在句末、标点符号前
- 每句最多 4 个引用

### 必须引用的内容
1. 具体数值（尺寸、厚度、间距、强度等级等）
2. 规范条文引用（GB、JGJ 等标准编号及条款）
3. 材料要求（品种、规格、性能指标）
4. 施工工艺要求（具体做法、步骤、工序）
5. 验收标准（允许偏差、检验方法）
6. 安全要求（防护措施、操作规范）

### 不需要引用的内容
- 通用常识性描述
- 过渡性语句和章节引导语
- 你自己的分析和归纳总结

### 示例

假设参考资料中有：
```
ID: 327
├── 来源: 建筑防水工程规范.pdf
└── 内容: 屋面防水层采用SBS改性沥青防水卷材，厚度不小于4mm...

ID: 45
├── 来源: 施工质量验收标准.pdf
└── 内容: 防水卷材搭接宽度长边不小于100mm，短边不小于150mm...
```

你的回答应包含：
> 屋面防水层采用SBS改性沥青防水卷材，厚度不小于4mm [ID:327]。卷材搭接宽度长边不小于100mm，短边不小于150mm [ID:45]。

**重要**：只引用上文提供的参考资料中实际存在的 ID 编号，不要编造不存在的 ID。
"""
